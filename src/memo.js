// Текст команды /памятка. Шаблоны вынесены отдельно, чтобы тест проверял, что бот разбирает их в заполненном виде.

export const ACCEPTED_TEMPLATE = `Ссылка на отчёт
Упоминание человека | [Отдел] Имя Фамилия [Ранг]
**Изменение баллов:**
Нет
-# -/+ Балов | Активности | Причина
---------------------------------
**[Количество баллов] баллов**
-# Минимум 50 баллов`;

export const REJECTED_TEMPLATE = `Ссылка на отчёт
Упоминание человека | [Отдел] Имя Фамилия [Ранг]
Причина отказа`;

const fence = (text) => `\`\`\`\n${text}\n\`\`\``;

export function memoMessages(botName) {
  const bot = botName ? ` «${botName}»` : '';
  return [
    [
      '**Памятка**',
      '',
      '**1. Перешлите отчёт боту**',
      '- Найдите отчёт «Delta Report System» в канале с отчётами.',
      '- Наведите на сообщение и нажмите «Переслать» (стрелка справа) или правый клик → «Переслать».',
      `- В списке выберите бота${bot} (можно найти по имени) и нажмите «Отправить». Пересылать нужно именно так, а не копировать текст.`,
      '- Бот ответит: «Отчёт: имя (ранг, отдел), баллы. Жду проверку».',
      '',
      '**2. Отправьте проверку**',
      '- Правый клик по отчёту в канале → «Копировать ссылку на сообщение».',
      `- Откройте чат с ботом${bot} (туда же, куда пересылали отчёт) и вставьте ссылку первой строкой.`,
      '- Дальше заполните по формату ниже. Между строками — Shift+Enter, упоминание — наберите @ и выберите человека.',
      '- Отправьте. Бот ответит «имя — баллы → тип премии» или «отказ: причина».',
      '',
      '**3. Так по каждому отчёту, потом получите формы**',
      '`/отчет` — формы по вашим проверкам. Каждая часть приходит отдельным блоком для копирования.',
      '`/статус` — чего не хватает, `/очистить` — начать заново.',
      '',
      '**Вручную, без пересылки**',
      '`/добавить-принятый` и `/добавить-отказанный` — внести отчёт по полям (ID, имя, ссылка, баллы, ранг, должность или причина).',
      '`/удалить-отчет` — удалить отчёт (принятый или отказанный) по ссылке.',
      '`/проверить-наличие` — у кого отчёт уже есть, у кого нет: имена и фамилии или ID через запятую.',
      'Одна ссылка — один отчёт: повтор ссылки даст ошибку. Отчётов у одного человека может быть сколько угодно, а в премию идёт один — принятый с максимумом баллов.',
    ].join('\n'),

    [
      '**Формат проверки: принятый отчёт**',
      fence(ACCEPTED_TEMPLATE),
      '- «Упоминание человека» — настоящее упоминание (@человек из списка) или его ID.',
      '- Если баллы менялись, вместо «Нет» укажите строки `-/+ Баллы | Активность | Причина`.',
      '- «[Количество баллов]» пишется без скобок, например `**90 баллов**`.',
    ].join('\n'),

    ['**Формат проверки: отказанный отчёт**', fence(REJECTED_TEMPLATE)].join('\n'),
  ];
}

/** Для тех, кто не зарегистрирован в системе. */
export function unregisteredMessage(userId) {
  return [
    '**Вы не зарегистрированы в системе.**',
    'Обратитесь к старшему составу: вас должны добавить командой `/старший-состав` (ранг 1, инструктор).',
    `Сообщите им ваш Discord ID: \`${userId}\``,
  ].join('\n');
}

/**
 * Для тех, у кого есть кто-то ниже по рангу.
 * addable — ранги, которые они вправе добавлять (например «[4] Куратор отдела»); canReports — есть ли общие команды.
 */
export function leadershipMessage({ level, addable, canReports }) {
  const lines = [
    `**Ваш ранг: ${level}**`,
    '`/старший-состав` присылает список рангов (число в скобках) и кнопки:',
    '- «Добавить»: ранг (цифра), ID, имя и фамилия, например `[Инст.Delta] Имя Фамилия`. Кто уже в списке, тот переносится на новый ранг.',
    '- «Убрать»: ID.',
    '- «Изменить имя»: ID и новое имя.',
    '- «Добавить отчёт»: ID того, за кого записываете; затем в личных сообщениях бота перешлите отчёт и отправьте проверку.',
    '- «Убрать отчёт»: ссылка на отчёт.',
    `Трогать можно только тех, кто ниже вас по рангу. Вам доступны: ${addable.join(', ')}.`,
  ];
  if (canReports) lines.push('`/общий-отчет` и `/статистика` — отчёты и статистика по всем.');
  return lines.join('\n');
}
